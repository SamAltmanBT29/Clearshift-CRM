/**
 * Asserts the ClearShift row conservation equation:
 * source = loaded + rejected + merged + skipped  AND  unaccounted = 0
 */
export function assertConservationEquation(summary: {
  totalSourceRows: number;
  loaded: number;
  rejected: number;
  merged: number;
  skipped: number;
}): {
  isConserved: boolean;
  unaccounted: number;
  status: 'OK' | 'NOT_CONSERVED';
} {
  const sumOfOutcomes =
    summary.loaded + summary.rejected + summary.merged + summary.skipped;
  const unaccounted = summary.totalSourceRows - sumOfOutcomes;
  const isConserved = unaccounted === 0;

  return {
    isConserved,
    unaccounted,
    status: isConserved ? 'OK' : 'NOT_CONSERVED',
  };
}

/**
 * Builds normalized candidate deduplication key for marketing lists.
 */
export function buildListExactKey(sourceSystem: string, sourceId: string): string {
  return `${sourceSystem.trim().toLowerCase()}#${sourceId.trim().toLowerCase()}`;
}

/**
 * Builds normalized candidate business deduplication key for lists based on name.
 */
export function buildListBusinessKey(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, ' ');
}

/**
 * Builds normalized candidate deduplication key for campaigns:
 * normalizedName#listId#campaignDate
 */
export function buildCampaignExactKey(
  name: string,
  listId: string,
  campaignDate: string
): string {
  return `${name.trim().toLowerCase()}#${listId.trim().toLowerCase()}#${campaignDate.trim()}`;
}

/**
 * Builds normalized candidate deduplication key for campaign members:
 * campaignId#contactId
 */
export function buildMemberExactKey(campaignId: string, contactId: string): string {
  return `${campaignId.trim().toLowerCase()}#${contactId.trim().toLowerCase()}`;
}

/**
 * Builds candidate key for contact consent:
 * contactId (strictly 1:1)
 */
export function buildConsentExactKey(contactId: string): string {
  return contactId.trim().toLowerCase();
}

/**
 * Evaluates whether a proposed consent status change satisfies BR-CRM4-01 monotonic opt-out.
 */
export function evaluateConsentMonotonicity(
  currentStatus: string | null | undefined,
  incomingStatus: string
): { permitted: boolean; reason?: string } {
  const curr = currentStatus?.trim().toLowerCase();
  const next = incomingStatus.trim().toLowerCase();

  if (curr === 'unsubscribed' && next === 'subscribed') {
    return {
      permitted: false,
      reason:
        'Domain Invariant Violation (BR-CRM4-01): Opt-out is strictly monotonic. Once unsubscribed, re-subscription via migration or bulk load is prohibited.',
    };
  }

  return { permitted: true };
}
