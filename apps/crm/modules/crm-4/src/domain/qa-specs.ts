export interface ColumnDefinition {
  name: string;
  pgType: string;
  nullable: boolean;
  default: string | null;
  constraints: string[];
  businessRule: string;
  example: string | number | boolean | null;
}

export interface TableDefinition {
  tableName: string;
  entityName: string;
  owner: string;
  description: string;
  columns: ColumnDefinition[];
  indexes: string[];
  checkConstraints: string[];
}

export interface RelationshipDefinition {
  relationshipId: string;
  fromTable: string;
  fromColumn: string;
  toTable: string;
  toColumn: string;
  cardinality: '1:1' | '1:N' | 'N:1';
  onDelete: 'RESTRICT' | 'CASCADE' | 'SET NULL';
  enforcement: 'Database Foreign Key' | 'Domain Application Guard' | 'API Projection';
  description: string;
}

export interface TraceabilityEntry {
  reqId: string;
  requirement: string;
  priority: 'Must' | 'Should' | 'Could';
  sourceDoc: string;
  category: 'Database' | 'Domain' | 'API' | 'Web' | 'Security' | 'Migration';
  testType: 'unit' | 'contract' | 'regression' | 'schema' | 'security' | 'integration' | 'e2e';
  testFile: string;
  testSuite: string;
  verificationEvidence: string;
}

export interface DefectScenario {
  scenarioId: string;
  category:
    | 'golden_baseline'
    | 'exact_duplicate'
    | 'malformed_syntax'
    | 'missing_required'
    | 'referential_orphan'
    | 'lifecycle_violation'
    | 'consent_violation'
    | 'formula_injection'
    | 'encoding_boundary';
  description: string;
  targetEntity: 'list' | 'campaign' | 'member' | 'consent';
  expectedOutcome: 'loaded' | 'rejected' | 'merged' | 'skipped';
  reasonCode?: string;
  expectedCountIn100: number;
  expectedCountIn1000: number;
  sampleRecord: Record<string, unknown>;
}

